export function relationById(id) { return RELATIONS.find((r) => r.id === id) || RELATIONS[0]; }
export function intentById(id) { return INTENTS.find((i) => i.id === id) || INTENTS[0]; }

/**
 * بيؤلّف رسالة واحدة. دالة نقية — مفيش شبكة ولا تخزين.
 * length: 'short' تسيب الجملة الأساسية بس، 'warm' بتزوّد خاتمة.
 */
export function composeOne({ relationId, intentId, dialect = 'egyptian', name = '', context = '', slot = 'manual', length = 'warm', emoji = true, seed = 1 }) {
  const rel = relationById(relationId);
  const intent = intentById(intentId);
  const rand = rng(seed);
  const bank = (BODIES[intent.id] && BODIES[intent.id][dialect]) || BODIES.general.egyptian;

  const body = bank[Math.floor(rand() * bank.length)];
  const parts = [];

  const opener = TIME_OPENERS[slot] && TIME_OPENERS[slot][dialect];
  const addr = name.trim() ? `يا ${name.trim()}` : rel.addr;
  // النداء بيتدمج مع تحية الوقت لو الاتنين موجودين، عشان ما يطلعش سطرين متلخبطين.
  parts.push(opener ? `${opener} ${addr}،` : `${addr}،`);
  parts.push(body);

  if (context.trim()) {
    // سياق المستخدم بيتحط كجملة مستقلة — من غير علامة نهاية بيلتصق باللي بعده.
    const c = context.trim();
    parts.push(/[.!؟?…]$/.test(c) ? c : c + '.');
  }
  if (length === 'warm') {
    const cl = CLOSERS[dialect] || CLOSERS.egyptian;
    parts.push(cl[Math.floor(rand() * cl.length)]);
  }

  let text = applyGender(parts.join(' '), rel.fem).replace(/\s+/g, ' ').trim();
  if (emoji) {
    const set = EMOJIS[intent.id] || EMOJIS.general;
    text += ' ' + set[Math.floor(rand() * set.length)];
  }
  return { text, theme: intent.label, intentId: intent.id };
}

/** بيرجّع عدد من الاقتراحات المختلفة (بذور مختلفة، ومن غير تكرار نصّي). */
export function compose(opts, count = 2) {
  const out = [];
  const baseSeed = opts.seed || 1;
  for (let i = 0; out.length < count && i < count * 8; i++) {
    const item = composeOne({ ...opts, seed: baseSeed + i * 7919 });
    if (!out.some((x) => x.text === item.text)) out.push(item);
  }
  return out;
}

/** رابط واتساب — المستخدم هو اللي بيدوس إرسال. مفيش إرسال تلقائي أبداً. */
export function whatsappLink(text, number = '') {
  const digits = String(number).replace(/\D/g, '');
  const q = `text=${encodeURIComponent(text)}`;
  return digits ? `https://wa.me/${digits}?${q}` : `https://wa.me/?${q}`;
}

/** كام يوم فاضل على مناسبة بصيغة MM-DD (بيلف للسنة الجاية لو عدّت). */
export function daysUntil(mmdd, today = new Date()) {
  if (!/^\d{2}-\d{2}$/.test(String(mmdd || ''))) return null;
  const [m, d] = mmdd.split('-').map(Number);
  if (m < 1 || m > 12 || d < 1 || d > 31) return null;
  const t = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  let next = new Date(t.getFullYear(), m - 1, d);
  if (next < t) next = new Date(t.getFullYear() + 1, m - 1, d);
  return Math.round((next - t) / 86400000);
}
