// محرّك تأليف الرسائل — محلي بالكامل، من غير أي نداء شبكة.
// ده قلب النسخة الويب: بيشتغل من غير مفتاح ومن غير سيرفر، وما بيطلعش منه
// أي بيانات برّه المتصفح. دالة نقية (نفس المدخلات = نفس المخرجات مع نفس الـ
// seed) عشان تتختبر على Node من غير متصفح.

// ---------- أدوات ----------

// توليد عشوائي بذرة (mulberry32): نفس الـ seed بيدّي نفس الاقتراح، فزرار
// "جدّد" بيدّي نتيجة مختلفة ومتوقّعة، والاختبارات تبقى حتمية.
export function rng(seed) {
  let t = seed >>> 0;
  return function next() {
    t += 0x6d2b79f5;
    let x = t;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

// صيغة المذكّر/المؤنث: النص بيتكتب طبيعي ومعاه بدائل جوّه {م|ف}.
// مثال: "قلبي معا{ك|كي}" → "معاك" للمذكّر، "معاكي" للمؤنث.
export function applyGender(text, isFem) {
  return String(text).replace(/\{([^{}|]*)\|([^{}|]*)\}/g, (_, m, f) => (isFem ? f : m));
}

